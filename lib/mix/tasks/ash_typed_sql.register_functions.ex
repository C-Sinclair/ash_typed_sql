if Code.ensure_loaded?(Igniter) do
  defmodule Mix.Tasks.AshTypedSql.RegisterFunctions do
    @shortdoc "Adds the custom expressions generated by `typed_sql_functions` to config.exs"

    @moduledoc """
    Adds every module generated by a `typed_sql_functions` section to `config :ash, :custom_expressions` in `config/config.exs`.

    Modules already listed are kept, and each generated module is added once. Run it after adding a `function` and running `mix ash.codegen`.

        $ mix ash_typed_sql.register_functions
    """

    use Igniter.Mix.Task

    @impl Igniter.Mix.Task
    def info(_argv, _composing_task), do: %Igniter.Mix.Task.Info{schema: [domains: :string]}

    @impl Igniter.Mix.Task
    def igniter(igniter) do
      Mix.Task.run("compile")

      modules =
        if(igniter.args.options[:domains],
          do: ["--domains", igniter.args.options[:domains]],
          else: []
        )
        |> Ash.Mix.Tasks.Helpers.domains!()
        |> Enum.flat_map(&Ash.Domain.Info.resources/1)
        |> Enum.uniq()
        |> AshTypedSql.Functions.Info.expression_modules()

      register(igniter, modules)
    end

    @doc "Adds `modules` to `config :ash, :custom_expressions`, keeping the modules already there."
    def register(igniter, []), do: igniter

    def register(igniter, modules) do
      Igniter.Project.Config.configure(
        igniter,
        "config.exs",
        :ash,
        [:custom_expressions],
        modules,
        updater: fn zipper ->
          Enum.reduce_while(modules, {:ok, zipper}, fn module, {:ok, zipper} ->
            case Igniter.Code.List.append_new_to_list(zipper, module) do
              {:ok, zipper} -> {:cont, {:ok, zipper}}
              :error -> {:halt, :error}
            end
          end)
        end
      )
    end
  end
end
